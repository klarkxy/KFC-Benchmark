/**
 * Deterministic pre-generated order streams.
 *
 * The judge owns the whole trajectory up front (doc 01 §6): every submission
 * running the same case sees identical arrival times, items, quantities and
 * values. This module is the generator; the host materializes order ids and
 * values from the frozen config at run time.
 *
 * Determinism: mulberry32(seed) from @kitchensched/contracts only. No
 * Math.random, no Date, no clock reads.
 */

import { mulberry32, type ItemQty, type Order, type PublicConfig, type Rng } from "@kitchensched/contracts";

import type { DemandCal } from "./kitchens.js";

export type StreamDifficulty = "easy" | "medium" | "complex";

export interface OrderStreamFile {
  version: "1";
  scenario_id: string;
  seed: number;
  /** Bumped whenever generated bytes would change for the same inputs. */
  generator_version: string;
  difficulty: StreamDifficulty;
  orders: { at_ms: number; items: ItemQty[] }[];
}

export const GENERATOR_VERSION = "scen/0.3.0";

export interface StreamOptions {
  /** Fixed arrival interval. */
  interval_ms: number;
  /** First arrival; the prep window is [0, start_at_ms). */
  start_at_ms: number;
  /** Arrivals must satisfy at_ms < end_at_ms. */
  end_at_ms: number;
}

export const DEFAULT_DEMAND: DemandCal = {
  line_count_weights: [1, 2, 2, 1],
  quantity_weights: [3, 5, 2],
};

/* ------------------------------------------------------------------------ */
/* Deterministic weighted sampling                                           */
/* ------------------------------------------------------------------------ */

/** Picks an index in [0, weights.length) proportionally to `weights`. */
function weightedIndex(rng: Rng, weights: readonly number[]): number {
  let total = 0;
  for (const w of weights) total += w;
  if (total <= 0) return 0;
  let r = rng() * total;
  for (let i = 0; i < weights.length; i += 1) {
    r -= weights[i] ?? 0;
    if (r < 0) return i;
  }
  return weights.length - 1;
}

/** Partial Fisher-Yates; returns the first `count` distinct entries. */
function pickDistinct<T>(rng: Rng, pool: readonly T[], count: number): T[] {
  const copy = pool.slice();
  const take = Math.min(count, copy.length);
  for (let i = 0; i < take; i += 1) {
    const j = i + Math.floor(rng() * (copy.length - i));
    const a = copy[i];
    const b = copy[j];
    if (a === undefined || b === undefined) continue;
    copy[i] = b;
    copy[j] = a;
  }
  return copy.slice(0, take);
}

function priceTable(config: PublicConfig): Map<string, number> {
  const table = new Map<string, number>();
  for (const item of config.items) {
    if (item.orderable && item.price_minor > 0) table.set(item.id, item.price_minor);
  }
  return table;
}

/** Orderable items in stable id order; never depends on array order in JSON. */
export function orderableItemIds(config: PublicConfig): string[] {
  return config.items
    .filter((item) => item.orderable && item.price_minor > 0)
    .map((item) => item.id)
    .sort();
}

function buildOneOrder(rng: Rng, catalog: readonly string[], demand: DemandCal): ItemQty[] {
  const lineIndex = weightedIndex(rng, demand.line_count_weights);
  const lineCount = lineIndex + 1;
  const chosen = pickDistinct(rng, catalog, lineCount);
  return chosen.map((item_id) => ({
    item_id,
    quantity: weightedIndex(rng, demand.quantity_weights) + 1,
  }));
}

/**
 * Builds a full order trajectory. Callers normally pass the config's
 * `end_at_ms`; it is a parameter only so a stream can be truncated for tests.
 */
export function generateOrderStream(
  config: PublicConfig,
  seed: number,
  opts: StreamOptions,
  demand: DemandCal = DEFAULT_DEMAND,
): OrderStreamFile {
  const rng = mulberry32(seed);
  const catalog = orderableItemIds(config);
  if (catalog.length === 0) {
    throw new Error(`generateOrderStream: ${config.scenario_id} has no orderable items`);
  }
  if (!Number.isSafeInteger(opts.interval_ms) || opts.interval_ms <= 0) {
    throw new Error(`generateOrderStream: interval_ms must be a positive integer, got ${opts.interval_ms}`);
  }
  if (!Number.isSafeInteger(opts.start_at_ms) || opts.start_at_ms < 0) {
    throw new Error(`generateOrderStream: start_at_ms must be a non-negative integer, got ${opts.start_at_ms}`);
  }
  if (!Number.isSafeInteger(opts.end_at_ms) || opts.end_at_ms <= 0) {
    throw new Error(`generateOrderStream: end_at_ms must be a positive integer, got ${opts.end_at_ms}`);
  }

  const orders: OrderStreamFile["orders"] = [];
  for (let at = opts.start_at_ms; at < opts.end_at_ms; at += opts.interval_ms) {
    orders.push({ at_ms: at, items: buildOneOrder(rng, catalog, demand) });
  }

  return {
    version: "1",
    scenario_id: config.scenario_id,
    seed,
    generator_version: GENERATOR_VERSION,
    difficulty: config.difficulty,
    orders,
  };
}

/* ------------------------------------------------------------------------ */
/* Host-side materialization                                                */
/* ------------------------------------------------------------------------ */

/**
 * Recomputes ids ("o1", "o2", … in arrival order) and values from the frozen
 * config. The stream file intentionally stores neither.
 */
export function materializeOrders(config: PublicConfig, stream: OrderStreamFile): Order[] {
  const prices = priceTable(config);
  return stream.orders.map((entry, index) => {
    let value_minor = 0;
    const items: ItemQty[] = entry.items.map((line) => {
      value_minor += (prices.get(line.item_id) ?? 0) * line.quantity;
      return { item_id: line.item_id, quantity: line.quantity };
    });
    return {
      id: `o${index + 1}`,
      arrived_at_ms: entry.at_ms,
      items,
      value_minor,
    };
  });
}

/** Aggregates used by the CLI summary and the calibration report. */
export interface StreamStats {
  readonly order_count: number;
  readonly first_at_ms: number | null;
  readonly last_at_ms: number | null;
  readonly total_value_minor: number;
  readonly total_units: number;
  readonly per_item: ReadonlyMap<string, { units: number; value_minor: number }>;
}

export function streamStats(config: PublicConfig, stream: OrderStreamFile): StreamStats {
  const orders = materializeOrders(config, stream);
  const per_item = new Map<string, { units: number; value_minor: number }>();
  let total_value_minor = 0;
  let total_units = 0;
  for (const order of orders) {
    total_value_minor += order.value_minor;
    for (const line of order.items) {
      total_units += line.quantity;
      const entry = per_item.get(line.item_id) ?? { units: 0, value_minor: 0 };
      entry.units += line.quantity;
      const price = config.items.find((it) => it.id === line.item_id)?.price_minor ?? 0;
      entry.value_minor += price * line.quantity;
      per_item.set(line.item_id, entry);
    }
  }
  return {
    order_count: orders.length,
    first_at_ms: orders[0]?.arrived_at_ms ?? null,
    last_at_ms: orders[orders.length - 1]?.arrived_at_ms ?? null,
    total_value_minor,
    total_units,
    per_item,
  };
}
